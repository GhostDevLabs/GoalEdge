"""Model-derived prices for real fixtures, and what "edge" can honestly mean.

The problem
-----------
Flashscore gives no odds. The engine can pick a winner from pure probabilities,
but `edge` and value bets need a *market* to disagree with. If we invent odds
from the model's own probabilities, then de-vigging them returns the model
probability again, so:

    edge = model_probability - implied_probability ≈ 0

by construction. That produced a front page where every real match read
"-3.7% below market" -- a number that looks like analysis but is only arithmetic
about a price we made up ourselves. It is not information, so it must not be
presented as if it were.

The honest approach
-------------------
Real fixtures ARE given prices, because:
  * a fixture with no price cannot be staked, tracked or settled, and
  * the headline pick, confidence and expected goals are all still meaningful.

But those prices are labelled `GoalEdge model` (not a book), and the API
marks the fixture as having **no independent market**. On such a fixture the UI
shows the model's own probability and fair odds, and simply does not claim an
edge -- because there is none to claim. `edge` is `None`, not `0.0`: "unknown"
and "zero" are different statements and the code keeps them apart.

Swap in a real odds feed (set `bookmaker` to the book's name and write real
`odds_*`) and everything downstream behaves as before, with genuine edges.
"""
from __future__ import annotations

#: The `bookmaker` value written for fixtures whose prices the model generated.
MODEL_BOOKMAKER = "GoalEdge model"


def is_model_priced(bookmaker: str | None) -> bool:
    """True when this fixture's prices were generated by us, not a real book.

    Used to suppress edge/value claims that would otherwise be tautological.
    """
    return bookmaker == MODEL_BOOKMAKER
