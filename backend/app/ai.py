"""AI analysis layer.

Two providers behind one interface:

* ``OpenAIProvider``  – used when ``OPENAI_API_KEY`` is configured. The
  statistical model's numbers are injected as ground truth in the prompt, so
  the LLM writes the narrative but never invents the probabilities.
* ``TemplateProvider`` – a deterministic sports-writer fallback built from the
  same numbers. Always available, no network, no key, no cost.

The structured prediction is the source of truth; the AI layer only explains it.
This matters: an LLM asked to "predict" a match hallucinates, an LLM asked to
explain a Poisson matrix produces genuinely useful copy.
"""
from __future__ import annotations

import asyncio
import json
from dataclasses import dataclass

import httpx

from .config import settings


@dataclass
class AiResult:
    provider: str
    model: str | None
    headline: str
    analysis: str
    betting_angle: str
    key_factors: list[str]
    risk_notes: list[str]


SYSTEM_PROMPT = """You are the lead football analyst for GoalEdge AI, a betting-tips \
publication. You write concise, confident, evidence-led previews for punters.

Hard rules:
- The probabilities, expected goals and odds given to you are GROUND TRUTH produced by \
a Dixon-Coles Poisson model. Never invent, round away or contradict them.
- Never claim certainty. Football is high variance; state the risk honestly.
- Reference the actual numbers you were given.
- Do not invent injuries, lineups, transfer news or quotes you were not given.
- Write in British English. No emojis. No markdown headings.

Respond with STRICT JSON only, exactly this shape:
{
  "headline": "<=70 char punchy one-liner",
  "analysis": "3 short paragraphs separated by \\n\\n, 120-190 words total",
  "betting_angle": "1-2 sentences naming the recommended selection and why the price is fair value",
  "key_factors": ["3 to 5 short bullet strings"],
  "risk_notes": ["2 to 3 short bullet strings"]
}"""


def _edge_line(prediction: dict) -> str:
    # edge is None when the fixture has no independent market (its price
    # was generated by this model). Formatting None as a percentage is a
    # TypeError, so the absence is stated in words instead.
    edge = prediction.get("best_edge")
    if edge is None:
        return "- Edge over market: not available (no book market on this fixture)"
    return f"- Edge over market: {edge:+.1%}"


def _match_brief(prediction: dict, fixture_meta: dict) -> str:
    """Render the model output as a compact brief for the LLM."""
    lines = [
        f"Fixture: {fixture_meta['home_team']} vs {fixture_meta['away_team']}",
        f"Competition: {fixture_meta['competition']}",
        f"Kick-off: {fixture_meta['kickoff']}",
        "",
        "MODEL OUTPUT (ground truth)",
        f"- 1X2: home {prediction['home_win']:.1%}, draw {prediction['draw']:.1%}, "
        f"away {prediction['away_win']:.1%}",
        f"- Expected goals: {fixture_meta['home_team']} {prediction['expected_home_goals']}, "
        f"{fixture_meta['away_team']} {prediction['expected_away_goals']} "
        f"(total {prediction['expected_total_goals']})",
        f"- Over 2.5: {prediction['over25']:.1%}  |  Under 2.5: {prediction['under25']:.1%}",
        f"- BTTS yes: {prediction['btts']:.1%}",
        f"- Model pick: {prediction['best_selection']} at "
        f"{prediction['best_probability']:.1%}"
        + (f" (odds {prediction['best_odds']})" if prediction.get('best_odds') else ""),
        _edge_line(prediction),
        f"- Confidence: {prediction['confidence']}/100 ({prediction['confidence_label']})",
    ]

    top = prediction.get("top_scorelines") or []
    if top:
        lines.append(
            "- Most likely scorelines: "
            + ", ".join(f"{c['home_goals']}-{c['away_goals']} ({c['probability']:.1%})" for c in top[:4])
        )

    hf, af = prediction.get("home_form"), prediction.get("away_form")
    if hf and af:
        lines += [
            "",
            "RECENT FORM",
            f"- {fixture_meta['home_team']}: {hf['form']} | {hf['points']}pts in {hf['played']} | "
            f"GF {hf['goals_for']} GA {hf['goals_against']} | home PPG {hf['home_ppg']} | "
            f"BTTS {hf['btts_rate']:.0%} | Over2.5 {hf['over25_rate']:.0%}",
            f"- {fixture_meta['away_team']}: {af['form']} | {af['points']}pts in {af['played']} | "
            f"GF {af['goals_for']} GA {af['goals_against']} | away PPG {af['away_ppg']} | "
            f"BTTS {af['btts_rate']:.0%} | Over2.5 {af['over25_rate']:.0%}",
        ]
    if hf and af and hf.get("position") and af.get("position"):
        lines.append(
            f"- League positions: {fixture_meta['home_team']} {hf['position']}th, "
            f"{fixture_meta['away_team']} {af['position']}th"
        )


    h2h = prediction.get("head_to_head") or {}
    if h2h.get("played"):
        lines += [
            "",
            f"HEAD TO HEAD (last {h2h['played']})",
            f"- {fixture_meta['home_team']} {h2h['home_wins']} wins, {h2h['draws']} draws, "
            f"{fixture_meta['away_team']} {h2h['away_wins']} wins",
            f"- Average total goals {h2h['avg_total_goals']}",
        ]

    if prediction.get("key_factors"):
        lines += ["", "MODEL NOTES: " + "; ".join(prediction["key_factors"][:5])]

    return "\n".join(lines)


class BaseProvider:
    name = "base"

    async def generate(self, brief: str, prediction: dict, fixture_meta: dict) -> AiResult:
        raise NotImplementedError


class TemplateProvider(BaseProvider):
    """Deterministic fallback writer. No key, no network, always works."""

    name = "goal-edge-rules"

    async def generate(self, brief: str, prediction: dict, fixture_meta: dict) -> AiResult:
        home = fixture_meta["home_team"]
        away = fixture_meta["away_team"]
        comp = fixture_meta["competition"]

        hw, d, aw = prediction["home_win"], prediction["draw"], prediction["away_win"]
        lam_h, lam_a = prediction["expected_home_goals"], prediction["expected_away_goals"]
        conf = prediction["confidence"]
        edge = prediction["best_edge"]
        sel = prediction["best_selection"]
        odds = prediction["best_odds"]

        fav, fav_p = (home, hw) if hw >= aw else (away, aw)
        if abs(hw - aw) < 0.05 and d > 0.27:
            headline = f"{home} vs {away}: the model sees a genuine coin flip"
        elif fav_p >= 0.62:
            headline = f"{fav} are the model's clear pick against {away if fav == home else home}"
        else:
            headline = f"{fav} hold the edge in a tight {comp.split(' - ')[-1]} contest"

        p1 = (
            f"The model makes {home} {hw:.0%} to win, {away} {aw:.0%} and the draw {d:.0%}. "
            f"Expected goals come out at {lam_h:.2f} for {home} and {lam_a:.2f} for {away}, "
            f"a projected total of {prediction['expected_total_goals']:.2f}. "
            f"That prices the match at {sel.lower()}"
            + (f" around {odds:.2f}" if odds else "")
            + f", which the engine rates {prediction['best_probability']:.0%} likely."
        )

        hf, af = prediction.get("home_form"), prediction.get("away_form")
        bits = []
        if hf and af:
            bits.append(
                f"{home} arrive on a {hf['form']} run with {hf['home_ppg']:.2f} points per home game, "
                f"while {away} have taken {af['away_ppg']:.2f} points per away fixture."
            )
            if hf["over25_rate"] or af["over25_rate"]:
                avg_over = (hf["over25_rate"] + af["over25_rate"]) / 2
                bits.append(
                    f"Goals history sits at {avg_over:.0%} of their combined matches going over 2.5."
                )
            if hf["btts_rate"] and af["btts_rate"]:
                avg_btts = (hf["btts_rate"] + af["btts_rate"]) / 2
                bits.append(f"Both-teams-to-score has landed in {avg_btts:.0%} of those games.")
        h2h = prediction.get("head_to_head") or {}
        if h2h.get("played"):
            bits.append(
                f"The last {h2h['played']} head-to-head meetings went "
                f"{h2h['home_wins']}-{h2h['draws']}-{h2h['away_wins']} to {home}, "
                f"averaging {h2h['avg_total_goals']:.2f} goals."
            )
        p2 = " ".join(bits) if bits else (
            "Recent sample sizes are small, so the rating leans on the league-average prior "
            "rather than short-term results."
        )

        top = (prediction.get("top_scorelines") or [{}])[0]
        p3 = (
            f"Confidence lands at {conf}/100 — {prediction['confidence_label'].lower()}. "
        )
        if top.get("probability"):
            p3 += (
                f"The most likely single scoreline, {top['home_goals']}-{top['away_goals']}, "
                f"is only {top['probability']:.1%} probable, which is the honest picture: "
                f"even a good read on a match leaves plenty of room for randomness. "
            )
        # `edge` is None when the fixture has no independent market -- its price
        # was generated by this model, so comparing the two would be circular.
        # Saying so is the honest option; inventing an edge would not be.
        if edge is None:
            p3 += (
                "There is no book market on this fixture, so no edge can be "
                "quoted: the price shown is the model's own and comparing it to "
                "itself would prove nothing. Read the probabilities, not an edge."
            )
        elif edge > 0.02:
            p3 += (
                f"The model sits {edge:+.1%} ahead of the de-vigged market price, so there is "
                f"a defensible value case rather than a hunch."
            )
        elif edge < -0.02:
            p3 += (
                f"The market prices this shorter than the model does ({edge:+.1%} edge), "
                f"so the disciplined play is a smaller stake or a pass."
            )
        else:
            p3 += "Model and market broadly agree, so this is a fair-priced call rather than an edge."

        angle = f"Recommended: {sel}"
        if odds:
            angle += f" at {odds:.2f}"
        angle += f". Fair price on the model's numbers is {prediction['markets'][0]['selections'][0]['fair_odds']:.2f}"
        angle += " or better — take it only while the price holds."

        return AiResult(
            provider=self.name,
            model=None,
            headline=headline,
            analysis="\n\n".join([p1, p2, p3]),
            betting_angle=angle,
            key_factors=prediction.get("key_factors", [])[:5],
            risk_notes=prediction.get("risk_notes", [])[:3],
        )


class OpenAIProvider(BaseProvider):
    name = "openai"

    def __init__(self, api_key: str, base_url: str, model: str):
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")
        self.model = model

    async def generate(self, brief: str, prediction: dict, fixture_meta: dict) -> AiResult:
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": f"Write the preview from this brief.\n\n{brief}"},
            ],
            "temperature": 0.45,
            "max_tokens": 900,
            "response_format": {"type": "json_object"},
        }
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        async with httpx.AsyncClient(timeout=settings.ai_timeout_seconds) as client:
            resp = await client.post(
                f"{self.base_url}/chat/completions", json=payload, headers=headers
            )
            resp.raise_for_status()
            data = resp.json()

        content = data["choices"][0]["message"]["content"]
        parsed = json.loads(content)
        return AiResult(
            provider=self.name,
            model=self.model,
            headline=str(parsed.get("headline", ""))[:140],
            analysis=str(parsed.get("analysis", "")),
            betting_angle=str(parsed.get("betting_angle", "")),
            key_factors=[str(x) for x in parsed.get("key_factors", [])][:6],
            risk_notes=[str(x) for x in parsed.get("risk_notes", [])][:4],
        )


def get_provider() -> BaseProvider:
    # Keep all generated analysis local, regardless of configured API keys.
    return TemplateProvider()


async def generate_analysis(prediction: dict, fixture_meta: dict) -> AiResult:
    """Generate the written analysis, degrading gracefully to the template."""
    brief = _match_brief(prediction, fixture_meta)
    provider = get_provider()
    try:
        result = await asyncio.wait_for(
            provider.generate(brief, prediction, fixture_meta),
            timeout=settings.ai_timeout_seconds + 5,
        )
        if not result.analysis.strip():
            raise ValueError("empty analysis")
        return result
    except Exception:
        # Any failure (no key, rate limit, timeout, malformed JSON) falls back.
        return await TemplateProvider().generate(brief, prediction, fixture_meta)


def build_one_line_summary(prediction: dict, fixture_meta: dict) -> str:
    """Cheap synchronous blurb used to populate list views without an LLM call."""
    home = fixture_meta["home_team"]
    away = fixture_meta["away_team"]
    sel = prediction["best_selection"]
    p = prediction["best_probability"]
    lam = prediction["expected_total_goals"]
    conf = prediction["confidence"]
    return (
        f"Model: {sel} ({p:.0%}, confidence {conf}/100). "
        f"Projected total {lam:.1f} goals, "
        f"1X2 {prediction['home_win']:.0%}/{prediction['draw']:.0%}/{prediction['away_win']:.0%}. "
        f"{home} vs {away}."
    )
