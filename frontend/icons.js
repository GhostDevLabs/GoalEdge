/**
 * Build an inline SVG icon.
 * @param {string} name  key in PATHS
 * @param {string} [extra] extra class names (e.g. "mi-fill")
 * @returns {string} HTML string, or "" for an unknown name
 */
export function icon(name, extra = "") {
  const d = PATHS[name];
  // An unknown name must not render a broken box; fail to nothing so the
  // surrounding text still reads correctly.
  if (!d) return "";
  const cls = extra ? `mi ${extra}` : "mi";
  // width/height attributes as well as the classes: an inline <svg> with no
  // intrinsic size falls back to 300x150 in some engines and zero in others if
  // only CSS sizes it. Setting both makes the rendered box deterministic.
  return (
    `<svg class="${cls}" viewBox="0 0 24 24" width="24" height="24" ` +
    `aria-hidden="true" focusable="false"><path d="${d}"/></svg>`
  );
}

